const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const assetsRoot = path.join(projectRoot, 'assets');
const outputPath = path.join(projectRoot, 'src', 'assets', 'localImages.js');

const categories = [
  { key: 'cities', dir: 'cities', exportName: 'localCityImages' },
  { key: 'dynasties', dir: 'dynasties', exportName: 'localDynastyImages' },
  { key: 'recipes', dir: 'recipes', exportName: 'localRecipeImages' },
];

function listImageFiles(dirPath) {
  if (!fs.existsSync(dirPath)) return [];
  return fs
    .readdirSync(dirPath)
    .filter((name) => /\.(png|jpe?g|webp)$/i.test(name))
    .sort((a, b) => a.localeCompare(b));
}

function toRequireLine(categoryDir, filename) {
  // output file lives at src/assets/localImages.js, so require path should go up two levels to /assets
  const rel = `../../assets/${categoryDir}/${filename}`.replace(/\\/g, '/');
  return `  ${JSON.stringify(filename)}: require(${JSON.stringify(rel)}),`;
}

function generate() {
  const header = `// AUTO-GENERATED by scripts/generate-local-images.js
// Do not edit by hand. Run: npm run gen:images
`;

  const blocks = categories.map(({ dir, exportName }) => {
    const dirPath = path.join(assetsRoot, dir);
    const files = listImageFiles(dirPath);
    const lines = files.map((f) => toRequireLine(dir, f));
    return `export const ${exportName} = {\n${lines.join('\n')}\n};\n`;
  });

  const helper = `
export function getLocalImage(category, filename) {
  if (!filename) return undefined;
  switch (category) {
    case 'cities':
      return localCityImages[filename];
    case 'dynasties':
      return localDynastyImages[filename];
    case 'recipes':
      return localRecipeImages[filename];
    default:
      return undefined;
  }
}
`;

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, `${header}\n${blocks.join('\n')}${helper}`, 'utf8');
  console.log(`Wrote ${path.relative(projectRoot, outputPath)}`);
}

generate();

