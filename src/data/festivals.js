// Helper function to get current solar term
export function getCurrentSolarTerm(date = new Date()) {
  const month = date.getMonth() + 1;
  const day = date.getDate();

  const solarTermDates = [
    { id: 'lichun', month: 2, day: 4 },
    { id: 'yushui', month: 2, day: 19 },
    { id: 'jingzhe', month: 3, day: 6 },
    { id: 'chunfen', month: 3, day: 21 },
    { id: 'qingming', month: 4, day: 5 },
    { id: 'guyu', month: 4, day: 20 },
    { id: 'lixia', month: 5, day: 6 },
    { id: 'xiaoman', month: 5, day: 21 },
    { id: 'mangzhong', month: 6, day: 6 },
    { id: 'xiazhi', month: 6, day: 21 },
    { id: 'xiaoshu', month: 7, day: 7 },
    { id: 'dashu', month: 7, day: 23 },
    { id: 'liqiu', month: 8, day: 8 },
    { id: 'chushu', month: 8, day: 23 },
    { id: 'bailu', month: 9, day: 8 },
    { id: 'qiufen', month: 9, day: 23 },
    { id: 'hanlu', month: 10, day: 8 },
    { id: 'shuangjiang', month: 10, day: 24 },
    { id: 'lidong', month: 11, day: 8 },
    { id: 'xiaoxue', month: 11, day: 22 },
    { id: 'daxue', month: 12, day: 7 },
    { id: 'dongzhi', month: 12, day: 22 },
    { id: 'xiaohan', month: 1, day: 6 },
    { id: 'daohan', month: 1, day: 20 },
  ];

  // Find the most recent solar term
  let currentTerm = null;
  for (const term of solarTermDates) {
    if (month === term.month && day >= term.day) {
      currentTerm = term;
    } else if (month > term.month || (month === 1 && term.month === 12)) {
      currentTerm = term;
    }
  }

  return festivals.find((f) => f.id === currentTerm?.id) ?? festivals[0];
}

/**
 * Get upcoming featured festivals
 * @param {Date} date - Current date
 * @param {number} count - Number of festivals to return
 * @returns {Array} Array of upcoming festivals
 */
export function getUpcomingFestivals(date = new Date(), count = 3) {
  const month = date.getMonth() + 1;
  const day = date.getDate();

  // Featured festivals with approximate dates (for sorting)
  const featuredFestivalsWithDates = [
    { id: 'spring-festival', month: 1, day: 22 }, // Approximate - lunar varies
    { id: 'lantern-festival', month: 2, day: 5 },
    { id: 'qingming', month: 4, day: 5 },
    { id: 'dragon-boat-festival', month: 6, day: 10 }, // Approximate - lunar varies
    { id: 'lixia', month: 5, day: 6 },
    { id: 'xiazhi', month: 6, day: 21 },
    { id: 'liqiu', month: 8, day: 8 },
    { id: 'qiufen', month: 9, day: 23 },
    { id: 'mid-autumn-festival', month: 9, day: 17 }, // Approximate - lunar varies
    { id: 'lidong', month: 11, day: 8 },
    { id: 'dongzhi', month: 12, day: 22 },
  ];

  // Sort festivals by proximity to current date
  const sorted = featuredFestivalsWithDates
    .map((f) => {
      const festival = festivals.find((fest) => fest.id === f.id);
      if (!festival) return null;

      // Calculate days until festival
      let daysUntil = (f.month - month) * 30 + (f.day - day);
      if (daysUntil < 0) daysUntil += 365; // Wrap around to next year

      return { ...festival, daysUntil };
    })
    .filter(Boolean)
    .sort((a, b) => a.daysUntil - b.daysUntil);

  return sorted.slice(0, count);
}